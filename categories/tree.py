#!/usr/bin/env python3
"""Read, check and export the category tree in kth-category-tree.md.

    python3 tree.py                    # check the tree, print counts per level
    python3 tree.py --print            # also print the parsed tree
    python3 tree.py --js FILE          # write the tree as JS for the slide (window.KTH_CATEGORY_TREE)

Tree format, between the markers <!-- tree:begin --> and <!-- tree:end -->:

    - `SH` Physics · *Fysik* <!-- note -->

one category per line, two spaces of indent per level, a `CODE` (KTH organisation code) when the
category is a unit in the line organisation, the title Indico gets, optionally the name in the
other language after " · " in *italics*, and optionally a note in an HTML comment. Everything
outside the markers is free text.

No Indico imports here: make-categories.py imports parse() from this file.
"""
import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path

DEFAULT_TREE = Path(__file__).with_name('kth-category-tree.md')
LINE = re.compile(r'^(?P<indent> *)- (?:`(?P<code>[^`]+)`\s+)?(?P<title>.+?)'
                  r'(?:\s+·\s+\*(?P<alt>[^*]+)\*)?(?:\s*<!--\s*(?P<note>.*?)\s*-->)?\s*$')
CODE = re.compile(r'^[A-Z][A-Z0-9]*$')


class TreeError(Exception):
    pass


def parse(path=DEFAULT_TREE):
    """Return the top-level nodes: dicts with title, alt, code, note, children, line."""
    roots, stack, inside = [], [], False
    for no, raw in enumerate(Path(path).read_text(encoding='utf-8').splitlines(), 1):
        if raw.strip() == '<!-- tree:begin -->':
            inside = True
            continue
        if raw.strip() == '<!-- tree:end -->':
            inside = False
            continue
        if not inside or not raw.strip():
            continue
        m = LINE.match(raw)
        if not m:
            raise TreeError(f'line {no}: not a tree line: {raw!r}')
        indent = len(m['indent'])
        if indent % 2:
            raise TreeError(f'line {no}: indent must be a multiple of two spaces')
        level = indent // 2
        if level > len(stack):
            raise TreeError(f'line {no}: indented more than one level below the line above')
        node = {'title': m['title'].strip(), 'alt': (m['alt'] or '').strip(), 'code': m['code'] or '',
                'note': m['note'] or '', 'children': [], 'line': no}
        del stack[level:]
        (stack[-1]['children'] if stack else roots).append(node)
        stack.append(node)
    if inside:
        raise TreeError('<!-- tree:begin --> without <!-- tree:end -->')
    if not roots:
        raise TreeError('no tree found (missing <!-- tree:begin --> marker?)')
    return roots


def walk(nodes, depth=0, parent=None):
    for n in nodes:
        yield n, depth, parent
        yield from walk(n['children'], depth + 1, n)


def check(roots):
    """Errors stop the Indico script; warnings are for the humans editing the tree."""
    errors, warnings = [], []
    codes = Counter(n['code'] for n, _, _ in walk(roots) if n['code'])
    for code, count in codes.items():
        if count > 1:
            errors.append(f'code {code} is used {count} times')
    for n, _, parent in walk(roots):
        if n['code'] and not CODE.match(n['code']):
            errors.append(f"line {n['line']}: code {n['code']!r} is not upper-case letters/digits")
        siblings = Counter(c['title'] for c in (parent['children'] if parent else roots))
        if siblings[n['title']] > 1:
            errors.append(f"line {n['line']}: two sibling categories are called {n['title']!r}")
        if parent and parent['code'] and n['code'] and not n['code'].startswith(parent['code']):
            warnings.append(f"line {n['line']}: {n['code']} is not under its parent's code {parent['code']}")
    return errors, warnings


def to_js(roots):
    def slim(n):
        d = {'t': n['title']}
        for key, short in (('alt', 'a'), ('code', 'c'), ('note', 'n')):
            if n[key]:
                d[short] = n[key]
        if n['children']:
            d['k'] = [slim(c) for c in n['children']]
        return d
    data = json.dumps([slim(n) for n in roots], ensure_ascii=False, separators=(',', ':'))
    return ('// Generated by categories/tree.py from categories/kth-category-tree.md. Do not edit.\n'
            f'window.KTH_CATEGORY_TREE = {data};\n')


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('tree', nargs='?', default=DEFAULT_TREE, help='tree file (default: %(default)s)')
    ap.add_argument('--print', action='store_true', help='print the parsed tree')
    ap.add_argument('--js', metavar='FILE', help='write the tree as JS for the slide deck')
    args = ap.parse_args(argv)
    try:
        roots = parse(args.tree)
    except TreeError as e:
        sys.exit(f'{args.tree}: {e}')
    errors, warnings = check(roots)
    for w in warnings:
        print(f'warning: {w}')
    for e in errors:
        print(f'ERROR: {e}')
    if args.print:
        for n, depth, _ in walk(roots):
            print('  ' * depth + (f"[{n['code']}] " if n['code'] else '') + n['title'])
    per_level = Counter(depth for _, depth, _ in walk(roots))
    coded = sum(1 for n, _, _ in walk(roots) if n['code'])
    print(f"{sum(per_level.values())} categories, {coded} with an organisation code; per level: "
          + ', '.join(f'{lvl + 1}: {cnt}' for lvl, cnt in sorted(per_level.items())))
    if errors:
        sys.exit(1)
    if args.js:
        Path(args.js).write_text(to_js(roots), encoding='utf-8')
        print(f'wrote {args.js}')


if __name__ == '__main__':
    main()
